// The Kotlin constants generator (#1011): an
// `internal object` of string constants for a module's commonMain. Kotlin/Native has no classpath resources,
// so data a module ships (the app version, the crypto catalog, the default OAuth client) is compiled in.
//
// Kotlin strings are UTF-16, so literals are escaped and chunked by UTF-16 code unit, as the task does.
package main

import (
	"flag"
	"fmt"
	"os"
	"sort"
	"strings"
	"unicode"
	"unicode/utf16"
)

// xorBase must match google_oauth.bzl's obfuscation.
const xorBase = 0x3B

// maxLiteralChars is the longest literal emitted in one piece: the JVM caps a constant-pool string at 65,535
// bytes of modified UTF-8, which a character takes up to 3 of.
const maxLiteralChars = 16000

type pairs map[string]string

func (p pairs) String() string { return fmt.Sprint(map[string]string(p)) }

func (p pairs) Set(v string) error {
	name, path, ok := strings.Cut(v, "=")
	if !ok {
		return fmt.Errorf("want NAME=path, got %q", v)
	}
	p[name] = path
	return nil
}

type names map[string]bool

func (n names) String() string { return fmt.Sprint(map[string]bool(n)) }

func (n names) Set(v string) error { n[v] = true; return nil }

func main() {
	pkg := flag.String("package", "", "the Kotlin package")
	object := flag.String("object", "", "the object's name")
	generatedBy := flag.String("generated_by", "", "what the header names as the generator")
	out := flag.String("out", "", "the .kt file to write")
	constants, obfuscated, trim := pairs{}, pairs{}, names{}
	flag.Var(constants, "constant", "NAME=file: a constant whose value is the file's text")
	flag.Var(obfuscated, "obfuscated", "NAME=file: a constant whose file holds xorObfuscate's hex")
	flag.Var(trim, "trim", "NAME: trim the constant's whitespace")
	flag.Parse()

	values, err := read(constants, trim)
	if err == nil {
		var hex map[string]string
		if hex, err = read(obfuscated, trim); err == nil {
			err = os.WriteFile(*out, []byte(render(*pkg, *object, *generatedBy, values, hex)), 0o644)
		}
	}
	if err != nil {
		fmt.Fprintln(os.Stderr, "kotlin_constants:", err)
		os.Exit(1)
	}
}

func read(files pairs, trim names) (map[string]string, error) {
	values := map[string]string{}
	for name, path := range files {
		body, err := os.ReadFile(path)
		if err != nil {
			return nil, err
		}
		values[name] = string(body)
		if trim[name] {
			values[name] = strings.TrimSpace(values[name])
		}
	}
	return values, nil
}

func sortedNames(m map[string]string) []string {
	var out []string
	for k := range m {
		out = append(out, k)
	}
	sort.Strings(out)
	return out
}

func render(pkg, object, generatedBy string, constants, obfuscated map[string]string) string {
	var b strings.Builder
	line := func(format string, args ...any) { fmt.Fprintf(&b, format+"\n", args...) }
	line("package %s", pkg)
	line("")
	line("// GENERATED by %s — do not edit.", generatedBy)
	line("internal object %s {", object)
	for _, name := range sortedNames(constants) {
		chunks := chunkLiteral(utf16.Encode([]rune(constants[name])))
		if len(chunks) == 1 {
			line("    const val %s: String = %s", name, kotlinStringLiteral(chunks[0]))
			continue
		}
		line("    val %s: String =", name)
		line("        listOf(")
		for _, chunk := range chunks {
			line("            %s,", kotlinStringLiteral(chunk))
		}
		line(`        ).joinToString("")`)
	}
	if len(obfuscated) > 0 {
		for _, name := range sortedNames(obfuscated) {
			hex := strings.TrimSpace(obfuscated[name])
			var codes []string
			for i := 0; i+4 <= len(hex); i += 4 {
				codes = append(codes, "0x"+hex[i:i+4])
			}
			line("    val %s: String = decode(intArrayOf(%s))", name, strings.Join(codes, ", "))
		}
		line("")
		line("    private fun decode(codes: IntArray): String =")
		line("        CharArray(codes.size) { index -> (codes[index] xor ((%d + index) and 0xFFFF)).toChar() }", xorBase)
		line("            .concatToString()")
	}
	line("}")
	return b.String()
}

// chunkLiteral splits a value into pieces of at most maxLiteralChars, never between a surrogate pair's halves.
func chunkLiteral(value []uint16) [][]uint16 {
	if len(value) <= maxLiteralChars {
		return [][]uint16{value}
	}
	var chunks [][]uint16
	for start := 0; start < len(value); {
		end := min(start+maxLiteralChars, len(value))
		if end < len(value) && isHighSurrogate(value[end-1]) {
			end--
		}
		chunks = append(chunks, value[start:end])
		start = end
	}
	return chunks
}

func isHighSurrogate(c uint16) bool { return c >= 0xD800 && c <= 0xDBFF }

func startsTemplate(value []uint16, i int) bool {
	if i >= len(value) {
		return false
	}
	c := value[i]
	if c == '_' || c == '{' || c == '`' {
		return true
	}
	// Kotlin's Char.isLetter(); a surrogate is not a letter.
	return !(c >= 0xD800 && c <= 0xDFFF) && unicode.IsLetter(rune(c))
}

func kotlinStringLiteral(value []uint16) string {
	var b strings.Builder
	b.WriteByte('"')
	for i, c := range value {
		switch {
		case c == '\\':
			b.WriteString(`\\`)
		case c == '"':
			b.WriteString(`\"`)
		// Escaped only where it would otherwise start a template: Qodana fails on redundant escapes.
		case c == '$' && startsTemplate(value, i+1):
			b.WriteString(`\$`)
		case c == '\n':
			b.WriteString(`\n`)
		case c == '\t':
			b.WriteString(`\t`)
		case c == '\r':
			b.WriteString(`\r`)
		case c < 0x20 || c > 0x7E:
			fmt.Fprintf(&b, `\u%04x`, c)
		default:
			b.WriteByte(byte(c))
		}
	}
	b.WriteByte('"')
	return b.String()
}
