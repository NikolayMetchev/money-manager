package com.moneymanager.tools.strategycatalog

import com.moneymanager.currency.IsoCurrency
import com.moneymanager.domain.model.CurrencyExportEntry
import com.moneymanager.domain.model.CurrencyListExport
import com.moneymanager.domain.strategy.StrategyFileNaming
import java.util.Locale
import java.util.Currency as JavaCurrency

/**
 * The ISO 4217 list as this JDK reports it: the one source for both the published catalog artifact and
 * the table bundled into the app (`utils/currency`'s `IsoCurrencies`). Names are English so the list is
 * the same whatever locale the build runs under.
 */
internal fun jdkIsoCurrencies(): List<IsoCurrency> =
    JavaCurrency
        .getAvailableCurrencies()
        .map { IsoCurrency(it.currencyCode, it.getDisplayName(Locale.ENGLISH), it.defaultFractionDigits) }
        .sortedBy { it.code }

/** The catalog's currency-list artifact for [currencies]. */
internal fun currencyListExport(currencies: List<IsoCurrency>): CurrencyListExport =
    CurrencyListExport(
        name = StrategyFileNaming.CURRENCIES_NAME,
        currencies = currencies.map { CurrencyExportEntry(it.code, it.name) },
    )

/** Renders [currencies] as the Kotlin source of `IsoCurrencies.kt`. */
internal fun renderIsoCurrenciesSource(currencies: List<IsoCurrency>): String =
    buildString {
        appendLine("package com.moneymanager.currency")
        appendLine()
        appendLine("// GENERATED by `bazel run //tools/strategy-catalog:generate_bundled_currencies` from java.util.Currency.")
        appendLine("// Do not edit by hand; IsoCurrencyTableTest fails when this falls behind the build's JDK.")
        appendLine()
        appendLine("/**")
        appendLine(" * The ISO 4217 currencies bundled into the app, sorted by code. New databases are seeded from this on")
        appendLine(" * every platform, so desktop, Android and native agree; the strategy catalog publishes the same list")
        appendLine(" * (as the JDK that built the site reports it) so an installed app can add codes it didn't ship with.")
        appendLine(" */")
        appendLine("object IsoCurrencies {")
        appendLine("    val all: List<IsoCurrency> =")
        appendLine("        listOf(")
        for (currency in currencies) {
            appendLine("            IsoCurrency(\"${currency.code}\", \"${currency.name.kotlinEscaped()}\", ${currency.fractionDigits}),")
        }
        appendLine("        )")
        appendLine("}")
    }

private fun String.kotlinEscaped(): String =
    replace("\\", "\\\\")
        .replace("\"", "\\\"")
        .replace("$", "\\$")
