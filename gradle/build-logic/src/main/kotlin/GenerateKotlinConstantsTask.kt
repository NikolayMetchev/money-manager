import org.gradle.api.DefaultTask
import org.gradle.api.file.DirectoryProperty
import org.gradle.api.provider.MapProperty
import org.gradle.api.provider.Property
import org.gradle.api.tasks.CacheableTask
import org.gradle.api.tasks.Input
import org.gradle.api.tasks.OutputDirectory
import org.gradle.api.tasks.TaskAction

/**
 * Generates an `internal object` of string constants as Kotlin source, for a module's `commonMain`
 * (`kotlin.srcDir(task)`). This is how build-time data reaches the app: Kotlin/Native has no classpath
 * resources, so data a module ships (the app version, the crypto catalog, the default OAuth client) is
 * compiled in on every platform rather than loaded from one.
 *
 * Secrets go in [obfuscatedConstants] already passed through [xorObfuscate], so the plaintext is never a
 * task input and so never lands in execution history or the build cache.
 */
@CacheableTask
abstract class GenerateKotlinConstantsTask : DefaultTask() {
    @get:Input
    abstract val packageName: Property<String>

    @get:Input
    abstract val objectName: Property<String>

    /** Constant name to value. */
    @get:Input
    abstract val constants: MapProperty<String, String>

    /** Constant name to [xorObfuscate] output; the generated property decodes it back to the plaintext. */
    @get:Input
    abstract val obfuscatedConstants: MapProperty<String, String>

    @get:OutputDirectory
    abstract val outputDirectory: DirectoryProperty

    init {
        outputDirectory.convention(project.layout.buildDirectory.dir("generated/kotlinConstants/$name"))
        obfuscatedConstants.convention(emptyMap())
        constants.convention(emptyMap())
    }

    @TaskAction
    fun generate() {
        val root = outputDirectory.get().asFile
        root.deleteRecursively()
        val pkg = packageName.get()
        val dir = root.resolve(pkg.replace('.', '/'))
        dir.mkdirs()
        dir.resolve("${objectName.get()}.kt").writeText(
            renderKotlinConstants(pkg, objectName.get(), path, constants.get(), obfuscatedConstants.get()),
        )
    }
}

private const val XOR_BASE = 0x3B

/**
 * Longest string literal emitted in one piece. The JVM caps a constant-pool string at 65,535 bytes of
 * modified UTF-8, which a character takes up to 3 of.
 */
internal const val MAX_LITERAL_CHARS = 16_000

/**
 * XOR-obfuscates [value] as hex for [GenerateKotlinConstantsTask.obfuscatedConstants], so a secret's literal
 * pattern (`GOCSPX-…`) never appears in the artifact for secret scanners to match. A speed bump, not real
 * protection.
 */
fun xorObfuscate(value: String): String =
    value
        .mapIndexed { index, ch -> "%04x".format(ch.code xor ((XOR_BASE + index) and 0xFFFF)) }
        .joinToString("")

internal fun renderKotlinConstants(
    packageName: String,
    objectName: String,
    generatedBy: String,
    constants: Map<String, String>,
    obfuscatedConstants: Map<String, String>,
): String =
    buildString {
        appendLine("package $packageName")
        appendLine()
        appendLine("// GENERATED by $generatedBy — do not edit.")
        appendLine("internal object $objectName {")
        for ((name, value) in constants.toSortedMap()) {
            val chunks = chunkLiteral(value)
            if (chunks.size == 1) {
                appendLine("    const val $name: String = ${kotlinStringLiteral(value)}")
            } else {
                appendLine("    val $name: String =")
                appendLine("        listOf(")
                chunks.forEach { appendLine("            ${kotlinStringLiteral(it)},") }
                appendLine("        ).joinToString(\"\")")
            }
        }
        if (obfuscatedConstants.isNotEmpty()) {
            for ((name, hex) in obfuscatedConstants.toSortedMap()) {
                val codes = hex.chunked(4).joinToString(", ") { "0x$it" }
                appendLine("    val $name: String = decode(intArrayOf($codes))")
            }
            appendLine()
            appendLine("    private fun decode(codes: IntArray): String =")
            appendLine("        CharArray(codes.size) { index -> (codes[index] xor (($XOR_BASE + index) and 0xFFFF)).toChar() }")
            appendLine("            .concatToString()")
        }
        appendLine("}")
    }

/** Splits [value] into pieces of at most [MAX_LITERAL_CHARS], never between the halves of a surrogate pair. */
internal fun chunkLiteral(value: String): List<String> {
    if (value.length <= MAX_LITERAL_CHARS) return listOf(value)
    val chunks = mutableListOf<String>()
    var start = 0
    while (start < value.length) {
        var end = minOf(start + MAX_LITERAL_CHARS, value.length)
        if (end < value.length && value[end - 1].isHighSurrogate()) end--
        chunks += value.substring(start, end)
        start = end
    }
    return chunks
}

internal fun kotlinStringLiteral(value: String): String =
    buildString {
        append('"')
        for (ch in value) {
            when {
                ch == '\\' -> append("\\\\")
                ch == '"' -> append("\\\"")
                ch == '$' -> append("\\$")
                ch == '\n' -> append("\\n")
                ch == '\t' -> append("\\t")
                ch == '\r' -> append("\\r")
                ch.code < 0x20 || ch.code > 0x7E -> append("\\u%04x".format(ch.code))
                else -> append(ch)
            }
        }
        append('"')
    }
